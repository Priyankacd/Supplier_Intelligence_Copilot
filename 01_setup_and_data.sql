-- A governed analytical view with explicit row grain and business definitions.
CREATE OR REPLACE VIEW VW_SUPPLIER_DELIVERY_ANALYTICS AS
SELECT
    f.DELIVERY_ID,
    s.SUPPLIER_ID,
    s.SUPPLIER_NAME,
    s.SUPPLIER_CODE,
    s.COUNTRY AS SUPPLIER_COUNTRY,
    s.SUPPLIER_TIER,
    p.PLANT_ID,
    p.PLANT_NAME,
    p.REGION AS PLANT_REGION,
    pt.PART_ID,
    pt.PART_NUMBER,
    pt.PART_DESCRIPTION,
    pt.CRITICALITY AS PART_CRITICALITY,
    f.PROMISED_DATE,
    f.ACTUAL_DATE,
    DATE_TRUNC('MONTH', f.PROMISED_DATE)::DATE AS PROMISED_MONTH,
    f.ORDER_QTY,
    f.RECEIVED_QTY,
    f.UNIT_COST,
    (f.ORDER_QTY * f.UNIT_COST)::NUMBER(12,2) AS ORDER_VALUE,
    IFF(f.ACTUAL_DATE <= f.PROMISED_DATE, 1, 0) AS ON_TIME_FLAG,
    IFF(f.ACTUAL_DATE > f.PROMISED_DATE, DATEDIFF('DAY', f.PROMISED_DATE, f.ACTUAL_DATE), 0) AS DELAY_DAYS,
    IFF(f.RECEIVED_QTY >= f.ORDER_QTY, 1, 0) AS FILL_COMPLETE_FLAG,
    (f.RECEIVED_QTY * f.UNIT_COST)::NUMBER(12,2) AS RECEIVED_VALUE
FROM FACT_DELIVERY f
JOIN DIM_SUPPLIER s ON f.SUPPLIER_ID = s.SUPPLIER_ID
JOIN DIM_PLANT p ON f.PLANT_ID = p.PLANT_ID
JOIN DIM_PART pt ON f.PART_ID = pt.PART_ID;
