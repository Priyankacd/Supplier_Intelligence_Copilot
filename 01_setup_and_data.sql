-- Synthetic manufacturing supplier data for interview practice.
-- Run in Snowsight using a role that can create database/schema/tables.
CREATE DATABASE IF NOT EXISTS MSI_COPILOT;
CREATE SCHEMA IF NOT EXISTS MSI_COPILOT.ANALYTICS;
USE DATABASE MSI_COPILOT;
USE SCHEMA ANALYTICS;

CREATE OR REPLACE TABLE DIM_SUPPLIER (
    SUPPLIER_ID NUMBER PRIMARY KEY,
    SUPPLIER_NAME VARCHAR(100),
    SUPPLIER_CODE VARCHAR(20),
    COUNTRY VARCHAR(50),
    SUPPLIER_TIER VARCHAR(20)
);

CREATE OR REPLACE TABLE DIM_PLANT (
    PLANT_ID NUMBER PRIMARY KEY,
    PLANT_NAME VARCHAR(100),
    REGION VARCHAR(50)
);

CREATE OR REPLACE TABLE DIM_PART (
    PART_ID NUMBER PRIMARY KEY,
    PART_NUMBER VARCHAR(30),
    PART_DESCRIPTION VARCHAR(200),
    CRITICALITY VARCHAR(20)
);

CREATE OR REPLACE TABLE FACT_DELIVERY (
    DELIVERY_ID NUMBER PRIMARY KEY,
    SUPPLIER_ID NUMBER,
    PLANT_ID NUMBER,
    PART_ID NUMBER,
    PROMISED_DATE DATE,
    ACTUAL_DATE DATE,
    ORDER_QTY NUMBER,
    RECEIVED_QTY NUMBER,
    UNIT_COST NUMBER(10,2),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

