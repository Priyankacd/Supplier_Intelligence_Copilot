USE DATABASE MSI_COPILOT;
USE SCHEMA ANALYTICS;

-- A. Data volumes and grain
SELECT COUNT(*) AS DELIVERY_ROWS, COUNT(DISTINCT DELIVERY_ID) AS DISTINCT_DELIVERIES
FROM FACT_DELIVERY;

-- B. Validate referential integrity (all should be zero)
SELECT
  SUM(IFF(s.SUPPLIER_ID IS NULL, 1, 0)) AS MISSING_SUPPLIER,
  SUM(IFF(p.PLANT_ID IS NULL, 1, 0)) AS MISSING_PLANT,
  SUM(IFF(pt.PART_ID IS NULL, 1, 0)) AS MISSING_PART
FROM FACT_DELIVERY f
LEFT JOIN DIM_SUPPLIER s ON f.SUPPLIER_ID = s.SUPPLIER_ID
LEFT JOIN DIM_PLANT p ON f.PLANT_ID = p.PLANT_ID
LEFT JOIN DIM_PART pt ON f.PART_ID = pt.PART_ID;

-- C. Independently calculate supplier OTD; compare to semantic-view result.
SELECT
  SUPPLIER_NAME,
  COUNT(*) AS DELIVERY_COUNT,
  ROUND(100.0 * AVG(ON_TIME_FLAG), 2) AS OTD_PCT,
  ROUND(AVG(DELAY_DAYS), 2) AS AVG_DELAY_DAYS
FROM VW_SUPPLIER_DELIVERY_ANALYTICS
GROUP BY SUPPLIER_NAME
ORDER BY OTD_PCT;

-- D. Trend by promised month
SELECT
  PROMISED_MONTH,
  COUNT(*) AS DELIVERY_COUNT,
  ROUND(100.0 * AVG(ON_TIME_FLAG), 2) AS OTD_PCT
FROM VW_SUPPLIER_DELIVERY_ANALYTICS
GROUP BY PROMISED_MONTH
ORDER BY PROMISED_MONTH;

-- E. Check impossible / suspicious data
SELECT *
FROM VW_SUPPLIER_DELIVERY_ANALYTICS
WHERE ORDER_QTY <= 0
   OR RECEIVED_QTY < 0
   OR UNIT_COST < 0
   OR PROMISED_DATE IS NULL
   OR ACTUAL_DATE IS NULL;

-- F. Check semantic-view metadata
SHOW SEMANTIC VIEWS IN SCHEMA MSI_COPILOT.ANALYTICS;
